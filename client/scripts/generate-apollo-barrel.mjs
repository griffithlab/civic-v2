#!/usr/bin/env node
// Regenerates src/app/generated/civic.apollo.ts as a compatibility barrel
// re-exporting the schema types plus every colocated *.gql.generated.ts
// module, so existing `@app/generated/civic.apollo` imports keep working.
// Runs as a graphql-codegen afterAllFileWrite hook (see .graphqlrc.yml);
// hook-passed file arguments are ignored.
//
// Also prunes orphaned *.gql.generated.ts files whose .gql source was
// removed or renamed, and fails on duplicate exported identifiers, which
// `export *` would otherwise silently drop.
import { globSync, readFileSync, rmSync, writeFileSync, existsSync } from 'node:fs'
import { relative, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const clientRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const generatedDir = join(clientRoot, 'src/app/generated')
const barrelPath = join(generatedDir, 'civic.apollo.ts')
const baseTypesPath = join(generatedDir, 'civic.apollo.types.ts')

const files = globSync('src/**/*.gql.generated.ts', { cwd: clientRoot })
  .filter((f) => !f.startsWith('src/app/generated/'))
  .sort()

// prune generated files whose .gql source no longer exists
const kept = []
for (const file of files) {
  const source = file.replace(/\.gql\.generated\.ts$/, '.gql')
  if (existsSync(join(clientRoot, source))) {
    kept.push(file)
  } else {
    rmSync(join(clientRoot, file))
    console.warn(`[barrel] pruned orphaned ${file} (no ${source})`)
  }
}

// collect exported identifiers; export * silently drops ambiguous names,
// so duplicates across modules must be a hard error
const exportPattern = /^export (?:type|const|class|enum|interface|function) (\w+)/gm
const owners = new Map()
const collisions = []
for (const file of [relative(clientRoot, baseTypesPath), ...kept]) {
  const content = readFileSync(join(clientRoot, file), 'utf8')
  for (const [, name] of content.matchAll(exportPattern)) {
    if (owners.has(name)) collisions.push(`${name}: ${owners.get(name)} and ${file}`)
    else owners.set(name, file)
  }
}
if (collisions.length > 0) {
  console.error('[barrel] duplicate exported identifiers, export * would drop them:')
  for (const c of collisions) console.error(`  ${c}`)
  process.exit(1)
}

const header = `/* eslint-disable */
// AUTO-GENERATED compatibility barrel - do not edit.
// Regenerated by scripts/generate-apollo-barrel.mjs (yarn generate-apollo).
`
const lines = kept.map(
  (f) => `export * from '${relative(generatedDir, join(clientRoot, f)).replace(/\.ts$/, '')}'`
)
const content = `${header}export * from './civic.apollo.types'\n${lines.join('\n')}\n`

// write only on change to keep watch mode quiet
if (!existsSync(barrelPath) || readFileSync(barrelPath, 'utf8') !== content) {
  writeFileSync(barrelPath, content)
  console.log(`[barrel] wrote ${kept.length + 1} re-exports to src/app/generated/civic.apollo.ts`)
}
